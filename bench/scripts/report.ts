import { readFile, writeFile } from "node:fs/promises";
import { availableParallelism } from "node:os";
import { join } from "node:path";

import * as corpus from "./corpus.ts";

import type { Result } from "./run.ts";

const DIR = join(import.meta.dirname, "..");

async function load(name: string): Promise<Result> {
	return JSON.parse(await readFile(join(DIR, "results", name), "utf8"));
}

function ms(value: number): string {
	return value >= 1000
		? `${(value / 1000).toFixed(2)}s`
		: `${value.toFixed(1)}ms`;
}

function mb(value: number): string {
	return `${Math.round(value / 1e6)}MB`;
}

function size(bytes: number): string {
	return bytes >= 1e6
		? `${(bytes / 1e6).toFixed(2)} MB`
		: `${Math.round(bytes / 1e3)} kB`;
}

let bun = await load("bun.json");
let node = await load("node.json");
let pages = await corpus.load();

let text = `# Benchmarks

> This file is generated by \`bun run bench all\`. Do not edit it by hand.

${bun.runtime} and ${node.runtime} on ${bun.cpu}, ${bun.date}.

## Results

| Workload | Bun | Node |
| --- | --- | --- |
| \`lint()\`, ${bun.pages} pages | ${ms(bun.lint.avg)} | ${ms(node.lint.avg)} |
| \`fs()\`, a site of ${bun.site.pages} pages, one thread | ${ms(bun.site.ms)} / ${mb(bun.site.rss)} | ${ms(node.site.ms)} / ${mb(node.site.rss)} |
| \`fs()\`, a site of ${bun.site.pages} pages, workers | ${ms(bun.workers.ms)} / ${mb(bun.workers.rss)} | ${ms(node.workers.ms)} / ${mb(node.workers.rss)} |

## Running

\`\`\`sh
$ bun run build          # build seolint, which the benchmarks import
$ bun run bench build    # download missing pages and write the site
$ bun run bench all      # build, run on Bun and Node, then write this file
\`\`\`

## Corpus

The corpus has ${pages.length} real pages, ${size(bun.bytes)} in total:

${pages.map((x) => `- ${x.name} (${size(Buffer.byteLength(x.html))})`).join("\n")}

The site has ${bun.site.pages / pages.length} copies of each page, in its own folder, with a \`robots.txt\` and a \`sitemap.xml\` that lists every page. Their links are relative to the original sites, so most become internal links, which the site checks look for in the site folder.

## Method

- **\`lint()\`** lints every corpus page once per iteration with the default rules, timed by [mitata](https://github.com/evanwashere/mitata). Each iteration starts with a collected heap. This is the cost of the checks for one page, without the file system or the site checks.
- **\`fs()\`** lints the whole site in a fresh process, as the CLI does. It includes reading files and the site checks. The time is the median of 5 samples. The "one thread" row sets \`workers: 1\`. The "workers" row uses the default, which is ${Math.floor(availableParallelism() / 2)} workers on this machine.
- **Memory** is the peak resident memory of the \`fs()\` process, as the median of 5 samples.
`;

await writeFile(join(DIR, "readme.md"), text);
console.log("Wrote bench/readme.md");
